TEST(Nfs3, TheTreeOfAReplyStaysInsideTheFrameAndTheReplayAgrees) {
    Flow flow(50000, 2049, "nfs3_tcp");
    const auto mk = [](const std::string &m) {
        const uint32_t v = 0x80000000u | static_cast<uint32_t>(m.size());
        return std::string{static_cast<char>(v >> 24), static_cast<char>(v >> 16), static_cast<char>(v >> 8), static_cast<char>(v)} + m;
    };
    flow.client(mk(kLookupCall)).server(mk(kLookupReply)).client(mk(kReaddirCall)).server(mk(kReaddirReply));
    flow.load();
    EXPECT_EQ(flow.packets()[1].info, "NFS v3 LOOKUP Reply (XID: 0x30000004), NFS3_OK fh=4041424344454647...");
    flow.expectReplayEqualsLoad();
}

