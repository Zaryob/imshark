TEST(DceRpcTower, ReadsTheFloorsOfAnIpTcpTowerAndANamedPipeTower) {
    const std::string tcp = raw(kTowerTcp), np = raw(kTowerNp);
    dissect::DceTower t;
    ASSERT_TRUE(dissect::parseEpmTower(reinterpret_cast<const uint8_t *>(tcp.data()), tcp.size(), t));
    EXPECT_EQ(t.uuid, kSrvsvc);
    EXPECT_EQ(t.version, 3u) << "major 3, minor 0";
    EXPECT_EQ(t.protocol, "ncacn_ip_tcp");
    EXPECT_EQ(t.port, 49667) << "the port is big-endian: c2 03 on the wire";
    EXPECT_EQ(t.host, "10.0.0.2");
    EXPECT_FALSE(t.udp);
    dissect::DceTower p;
    ASSERT_TRUE(dissect::parseEpmTower(reinterpret_cast<const uint8_t *>(np.data()), np.size(), p));
    EXPECT_EQ(p.protocol, "ncacn_np");
    EXPECT_EQ(p.address, "\\PIPE\\srvsvc");
    EXPECT_EQ(p.port, 0);
}

TEST(DceRpcTower, RejectsTowersThatDoNotFit) {
    const std::string tcp = raw(kTowerTcp);
    dissect::DceTower t;
    for (size_t cut = 0; cut + 1 < tcp.size(); ++cut) {
        dissect::DceTower x;
        const bool ok = dissect::parseEpmTower(reinterpret_cast<const uint8_t *>(tcp.data()), cut, x);
        if (cut < 30) EXPECT_FALSE(ok) << cut;   // not even the interface floor
    }
    EXPECT_FALSE(dissect::parseEpmTower(nullptr, 0, t));
    std::string bad = tcp;
    bad[0] = 0;   // zero floors
    bad[1] = 0;
    EXPECT_FALSE(dissect::parseEpmTower(reinterpret_cast<const uint8_t *>(bad.data()), bad.size(), t));
}

TEST(DceRpcEpmAnswer, MapAndLookupAnswersAreRead) {
    const auto parse = [](uint16_t opnum, bool little, const std::string &stub, std::vector<dissect::DceTower> &out) {
        return dissect::parseEpmAnswer(opnum, little, reinterpret_cast<const uint8_t *>(stub.data()), stub.size(), out);
    };
    std::vector<dissect::DceTower> t;
    ASSERT_TRUE(parse(3, true, raw(kMapOne), t));
    ASSERT_EQ(t.size(), 1u);
    EXPECT_EQ(t[0].port, 49667);
    t.clear();
    ASSERT_TRUE(parse(3, false, raw(kMapBe), t)) << "big-endian NDR";
    ASSERT_EQ(t.size(), 1u);
    EXPECT_EQ(t[0].uuid, kSrvsvc);
    t.clear();
    ASSERT_TRUE(parse(3, true, raw(kMapTwo), t));
    ASSERT_EQ(t.size(), 2u);
    EXPECT_EQ(t[1].protocol, "ncacn_np");
    t.clear();
    ASSERT_TRUE(parse(2, true, raw(kLookup), t));
    ASSERT_EQ(t.size(), 3u);
    EXPECT_EQ(t[0].uuid, kSrvsvc);
    EXPECT_EQ(t[1].uuid, kSamr);
    EXPECT_TRUE(t[2].udp);
    EXPECT_EQ(t[2].port, 49700);
    t.clear();
    EXPECT_FALSE(parse(1, true, raw(kMapOne), t)) << "only opnum 2 and 3 are answers with towers";
}

TEST(DceRpcEpmAnswer, TruncatedAndMutatedAnswersNeverReadOutside) {
    std::mt19937 rng(0x6d70);
    for (const char *hexText: {kMapOne, kMapBe, kMapTwo, kLookup}) {
        const std::string good = raw(hexText);
        for (size_t cut = 0; cut <= good.size(); ++cut) {
            std::vector<dissect::DceTower> t;
            const std::string part = good.substr(0, cut);
            dissect::parseEpmAnswer(3, true, reinterpret_cast<const uint8_t *>(part.data()), part.size(), t);
            dissect::parseEpmAnswer(2, true, reinterpret_cast<const uint8_t *>(part.data()), part.size(), t);
            EXPECT_LE(t.size(), 2u * DceRpcTable::kMaxTowers);
        }
        for (int round = 0; round < 400; ++round) {
            std::string m = good;
            for (int k = 0; k < 1 + round % 4; ++k) m[rng() % m.size()] = static_cast<char>(rng());
            std::vector<dissect::DceTower> t;
            dissect::parseEpmAnswer(3, round % 2 == 0, reinterpret_cast<const uint8_t *>(m.data()), m.size(), t);
            dissect::parseEpmAnswer(2, round % 2 == 0, reinterpret_cast<const uint8_t *>(m.data()), m.size(), t);
        }
    }
}

TEST(DceRpcTable, AnAcceptedContextNamesTheInterfaceOfLaterRequests) {
    Table x;
    x.observe("s", 1, bind(1, {{0, kSrvsvc, 3}, {1, kSamr, 1}}));
    EXPECT_EQ(x.t.context("s", 0), nullptr) << "proposed, not yet accepted";
    x.observe("s", 2, bindAck(1, {0, 2}));
    ASSERT_NE(x.t.context("s", 0), nullptr);
    EXPECT_EQ(x.t.context("s", 0)->uuid, kSrvsvc);
    EXPECT_EQ(x.t.context("s", 1), nullptr) << "provider-rejection";
    const DceNote *r = x.observe("s", 3, request(2, 0, 15));
    EXPECT_EQ(r->iface, kSrvsvc);
    EXPECT_EQ(r->ifVersion, 3u);
    EXPECT_EQ(r->opnum, 15);
    EXPECT_EQ(r->flags & DceNote::kUnknownContext, 0);
    const DceNote *u = x.observe("s", 4, request(3, 1, 4));
    EXPECT_TRUE(u->flags & DceNote::kUnknownContext) << "context 1 was rejected";
    EXPECT_TRUE(u->iface.empty());
    const DceNote *other = x.observe("other", 5, request(4, 0, 4), "", "10.0.0.2", kSamr);
    EXPECT_EQ(other->iface, kSamr) << "assumed from the fallback";
    EXPECT_TRUE(other->flags & DceNote::kAssumed);
    EXPECT_TRUE(other->flags & DceNote::kUnknownContext);
}

TEST(DceRpcTable, AResponseLearnsTheOpnumAndPacketOfItsRequest) {
    Table x;
    x.observe("s", 1, bind(1, {{0, kSrvsvc, 3}}));
    x.observe("s", 2, bindAck(1, {0}));
    x.observe("s", 3, request(7, 0, 15));
    x.observe("s", 4, request(8, 0, 9));
    const DceNote *r8 = x.observe("s", 5, response(8, 0));
    EXPECT_TRUE(r8->flags & DceNote::kMatched);
    EXPECT_EQ(r8->opnum, 9);
    EXPECT_EQ(r8->requestPacket, 4u);
    const DceNote *r7 = x.observe("s", 6, response(7, 0));
    EXPECT_EQ(r7->opnum, 15);
    EXPECT_EQ(r7->requestPacket, 3u);
    const DceNote *none = x.observe("s", 7, response(99, 0));
    EXPECT_FALSE(none->flags & DceNote::kMatched);
    DcePdu fault = response(7, 0);
    fault.type = dissect::kDceFault;
    EXPECT_TRUE(x.observe("s", 8, fault)->flags & DceNote::kMatched);
    EXPECT_EQ(x.observe("t", 9, response(8, 0))->flags & DceNote::kMatched, 0) << "another stream";
}

TEST(DceRpcTable, FragmentsOfOneCallAreChainedAndTheEarlierOnesLearnWhereItCompleted) {
    Table x;
    x.observe("s", 1, request(5, 0, 3, true, false), "aaaa");
    x.observe("s", 2, request(5, 0, 3, false, false), "bbbbbb");
    const DceNote *last = x.observe("s", 3, request(5, 0, 3, false, true), "cc");
    ASSERT_TRUE(last->flags & DceNote::kCompletes);
    const auto *m = x.t.message(last->message);
    ASSERT_NE(m, nullptr);
    EXPECT_EQ(m->bytes, 12u);
    EXPECT_EQ(m->fragments, 3);
    EXPECT_EQ(m->packets, (std::vector<uint32_t>{1, 2, 3}));
    EXPECT_TRUE(x.t.note(1, -1, 0)->flags & DceNote::kCompletedLater);
    EXPECT_EQ(x.t.note(1, -1, 0)->completedIn, 3u);
    EXPECT_EQ(x.t.note(2, -1, 0)->completedIn, 3u);
    EXPECT_FALSE(last->flags & DceNote::kCompletedLater);
    EXPECT_EQ(x.t.noteCount(), 3u);
}

