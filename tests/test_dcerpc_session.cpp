TEST(DceRpcTable, ConnectionlessFragmentsMayArriveInAnyOrderAndRepeat) {
    // fragment numbers 2 (last), 0, 1: the chain completes with the middle one
    const auto cl = [](uint32_t seq, uint32_t frag, bool last) {
        DcePdu p = request(seq, 0, 7, frag == 0, last);
        p.connectionless = true;
        p.fragment = frag;
        p.interfaceUuid = kSrvsvc;
        p.interfaceVersion = 3;
        return p;
    };
    Table x;
    x.observe("cl:act", 10, cl(4, 2, true), "33");
    x.observe("cl:act", 11, cl(4, 0, false), "1111");
    const DceNote *dup = x.observe("cl:act", 12, cl(4, 0, false), "1111");
    EXPECT_TRUE(dup->flags & DceNote::kDuplicate);
    const DceNote *done = x.observe("cl:act", 13, cl(4, 1, false), "2222");
    ASSERT_TRUE(done->flags & DceNote::kCompletes);
    EXPECT_EQ(done->iface, kSrvsvc) << "named by the header, no Bind";
    EXPECT_EQ(x.t.message(done->message)->packets, (std::vector<uint32_t>{11, 13, 10}));
    EXPECT_EQ(x.t.message(done->message)->bytes, 10u);
    EXPECT_EQ(x.t.note(10, -1, 0)->completedIn, 13u);
    EXPECT_EQ(x.t.note(11, -1, 0)->completedIn, 13u);
    EXPECT_FALSE(x.t.note(12, -1, 0)->flags & DceNote::kCompletedLater);
}

