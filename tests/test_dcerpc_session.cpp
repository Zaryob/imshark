    DcePdu bind(uint32_t call, std::vector<dissect::DceContext> contexts) {
        DcePdu p;
        p.type = dissect::kDceBind;
        p.callId = call;
        p.contexts = std::move(contexts);
        return p;
    }
    DcePdu bindAck(uint32_t call, std::vector<uint16_t> results) {
        DcePdu p;
        p.type = dissect::kDceBindAck;
        p.callId = call;
        p.results = std::move(results);
        return p;
    }
    DcePdu request(uint32_t call, uint16_t ctx, uint16_t opnum, bool first = true, bool last = true) {
        DcePdu p;
        p.type = dissect::kDceRequest;
        p.callId = call;
        p.contextId = ctx;
        p.opnum = opnum;
        p.first = first;
        p.last = last;
        return p;
    }
    DcePdu response(uint32_t call, uint16_t ctx, bool first = true, bool last = true) {
        DcePdu p;
        p.type = dissect::kDceResponse;
        p.callId = call;
        p.contextId = ctx;
        p.first = first;
        p.last = last;
        return p;
    }

    struct Table {
        DceRpcTable t;
        bool lost = false;
        const DceNote *observe(const std::string &stream, uint32_t packet, const DcePdu &pdu, const std::string &stub = "", const std::string &server = "10.0.0.2",
                               const std::string &fallback = "", int64_t seq = -1, uint8_t index = 0) {
            return t.observe(stream, packet, seq, index, pdu, stub, server, fallback, 64u << 20, lost);
        }
    };
