TEST(DceRpcTable, TheBudgetRunsOutAndTheTableSaysSo) {
    DceRpcTable t;
    bool lost = false;
    const DcePdu p = request(1, 0, 3, true, false);
    EXPECT_NE(t.observe("s", 1, -1, 0, p, "x", "", "", 1u << 20, lost), nullptr);
    EXPECT_FALSE(lost);
    DceRpcTable small;
    EXPECT_EQ(small.observe("s", 1, -1, 0, p, "x", "", "", 200, lost), nullptr);
    EXPECT_TRUE(lost);
    lost = false;
    DceRpcTable tiny;   // room for the note of a chain but not for another fragment
    size_t used = 0;
    for (uint32_t i = 1; i < 2000 && !lost; ++i) {
        tiny.observe("s", i, -1, 0, request(i, 0, 3, true, false), std::string(100, 'x'), "", "", 20000, lost);
        used = tiny.memory();
    }
    EXPECT_TRUE(lost);
    EXPECT_LE(used, 20000u);
}

TEST(DceRpcTable, AClearedTableForgetsEverything) {
    Table x;
    x.observe("epm", 1, request(2, 0, 3), "", "10.0.0.2", dissect::kDceEpmUuid);
    x.observe("epm", 2, response(2, 0), raw(kMapOne), "10.0.0.2", dissect::kDceEpmUuid);
    ASSERT_GT(x.t.memory(), 0u);
    x.t.clear();
    EXPECT_EQ(x.t.memory(), 0u);
    EXPECT_EQ(x.t.noteCount(), 0u);
    EXPECT_EQ(x.t.endpointCount(), 0u);
}
