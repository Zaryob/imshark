    void load(Flow &flow, std::initializer_list<const char *> names) {
        flow.asUdp();
        for (const char *n: names) {
            for (const auto &e: kAll) {
                if (std::string(e.name) == n) flow.client(e.call).server(e.reply);
            }
        }
        flow.load();
    }
