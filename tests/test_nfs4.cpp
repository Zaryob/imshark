TEST(Nfs4, EveryExchangeShowsItsOperationsAndTheirResults) {
    Flow flow(50000, 2049, "nfs4_all");
    flow.asUdp();
    for (const auto &e: kAll) flow.client(e.call).server(e.reply);
    flow.load();
    const auto &k = flow.packets();
    ASSERT_EQ(k.size(), sizeof(kAll) / sizeof(kAll[0]) * 2);
    for (size_t i = 0; i < sizeof(kAll) / sizeof(kAll[0]); ++i) {
        EXPECT_EQ(k[2 * i].protocol, "NFSv4") << kAll[i].name;
        EXPECT_EQ(k[2 * i].info, kAll[i].callInfo) << kAll[i].name;
        EXPECT_EQ(k[2 * i + 1].protocol, "NFSv4") << kAll[i].name;
        EXPECT_EQ(k[2 * i + 1].info, kAll[i].replyInfo) << kAll[i].name;
        EXPECT_TRUE(matches("nfs.status >= 0 && rpc.matched && nfs.version == 4 && nfs.proc == 1", k[2 * i + 1])) << kAll[i].name;
    }
    flow.expectReplayEqualsLoad();
}

